"""Merge the two verified bibliographies into paper/refs.bib (the one main.tex reads).

    python -I paper/merge_bib.py

refs_core.bib (the papers the novelty argument rests on) and refs_related.bib (the wider
related work) were verified separately (research_log/lit_core.md, lit_related.md). A key in
both must describe the same paper: the script checks that the DOI (or arXiv id) and the title
agree, keeps the core entry, and stops otherwise.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def entries(path: Path) -> dict:
    parts = re.split(r"(?m)^(?=@)", path.read_text(encoding="utf-8"))
    out = {}
    for p in parts[1:]:
        m = re.match(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", p)
        if not m:
            raise SystemExit(f"{path.name}: cannot parse entry starting {p[:60]!r}")
        if m.group(2) in out:
            raise SystemExit(f"{path.name}: key {m.group(2)} twice")
        out[m.group(2)] = p.strip()
    return out


def field(entry: str, name: str) -> str:
    m = re.search(rf"(?im)^\s*{name}\s*=\s*\{{(.*)\}}\s*,?\s*$", entry)
    return re.sub(r"[{}\s]+", " ", m.group(1)).strip().lower() if m else ""


def for_print(entry: str) -> str:
    """The entry as the reference list should show it. The `note` fields of the two source files record how
    each entry was verified (kept there); a reference list should not print them. An arXiv-only entry keeps a
    short note naming its arXiv id, since that is its only venue."""
    m = re.search(r"(?im)^\s*note\s*=\s*\{(.*)\}\s*(,?)\s*$\n?", entry)
    if not m:
        return entry
    keep = ""
    if m.group(1).strip().lower().startswith("arxiv preprint"):
        eprint = field(entry, "eprint")
        keep = f"  note          = {{arXiv preprint arXiv:{eprint}}}{m.group(2)}\n" if eprint else ""
    return entry[:m.start()] + keep + entry[m.end():]


def main() -> int:
    core = entries(HERE / "refs_core.bib")
    rel = entries(HERE / "refs_related.bib")
    for k in sorted(set(core) & set(rel)):
        a, b = core[k], rel[k]
        same_id = (field(a, "doi") and field(a, "doi") == field(b, "doi")) or \
                  (field(a, "eprint") and field(a, "eprint") == field(b, "eprint"))
        if not same_id or field(a, "title") != field(b, "title"):
            raise SystemExit(f"key {k} names two different papers; fix one of the files")
    merged = dict(core)
    merged.update({k: v for k, v in rel.items() if k not in core})
    head = ("% refs.bib -- generated by paper/merge_bib.py from refs_core.bib and refs_related.bib; "
            "do not edit by hand.\n% Every entry was verified against Crossref / arXiv / Semantic Scholar / "
            "the publisher (see research_log/lit_core.md and lit_related.md);\n% the verification notes stay in "
            "the two source files and are left out here, so the reference list does not print them.\n\n")
    (HERE / "refs.bib").write_text(head + "\n\n".join(for_print(merged[k]) for k in sorted(merged)) + "\n",
                                   encoding="utf-8")
    print(f"refs.bib: {len(merged)} entries ({len(core)} core + {len(rel)} related, "
          f"{len(set(core) & set(rel))} shared keys checked)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
